#!/usr/bin/env bash
# Build one output per list. allow/<name>.txt (AdGuard syntax) is the source of truth.
# Outputs:
#   dist/adguard/<name>.txt   AdGuard rules, subscribable per list
#   dist/pihole/<name>.txt    Pi-hole regex allowlist (matches each host and its subdomains)
set -euo pipefail
cd "$(dirname "$0")/.."
rm -rf dist
mkdir -p dist/adguard dist/pihole

for src in allow/*.txt; do
  name=$(basename "$src" .txt)

  {
    echo "! generated by scripts/build.sh from $src; edit that file instead"
    cat "$src"
  } > "dist/adguard/$name.txt"

  {
    echo "# generated by scripts/build.sh from $src; edit that file instead"
    grep -E '^@@\|\|[^ ]+\^$' "$src" \
      | sed -E 's/^@@\|\|//; s/\^$//' \
      | sort -u \
      | sed -E 's/\./\\./g; s/^/(\\.|^)/; s/$/$/'
  } > "dist/pihole/$name.txt"
done
