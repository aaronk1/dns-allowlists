#!/usr/bin/env bash
# Build dist/ from allow/*.txt (AdGuard syntax is the source of truth).
# Outputs:
#   dist/adguard.txt   combined AdGuard rules, subscribable as one URL
#   dist/pihole.txt    Pi-hole regex allowlist (matches each host and its subdomains)
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p dist

{
  echo "! generated by scripts/build.sh; edit allow/*.txt instead"
  cat allow/*.txt
} > dist/adguard.txt

{
  echo "# generated by scripts/build.sh; edit allow/*.txt instead"
  grep -hE '^@@\|\|[^ ]+\^$' allow/*.txt \
    | sed -E 's/^@@\|\|//; s/\^$//' \
    | sort -u \
    | sed -E 's/\./\\./g; s/^/(\\.|^)/; s/$/$/'
} > dist/pihole.txt
